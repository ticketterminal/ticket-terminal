import {parseHTML} from 'linkedom';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../..',import.meta.url));
const {window,document}=parseHTML(fs.readFileSync(root+'/public/index.html','utf8'));
let hidden=false;
Object.defineProperty(document,'hidden',{configurable:true,get:()=>hidden});
const calls=[];
let revision=0;
const realSetTimeout=globalThis.setTimeout;
globalThis.setTimeout=(callback,delay,...args)=>delay===5000 ? realSetTimeout(callback,0,...args) : realSetTimeout(callback,delay,...args);
Object.assign(globalThis,{window,document,location:{hash:'#/'},localStorage:{getItem:()=>null,setItem:()=>{}},Event:window.Event,
  fetch:async url=>{
    calls.push(url);
    const path=String(url).split('?w=')[0];
    let body={ok:true};
    if(path==='/api/running-processes') body={ok:true,running:['T-1'],working:revision?['T-1']:[],activity:{'T-1':revision}};
    if(path.startsWith('/api/ticket-costs')) body={ok:true,costs:{}};
    if(path==='/api/ticket-memory-usage') body={ok:true,usage:{}};
    return {ok:true,status:200,json:async()=>body};
  }});
const {pollAgentActivity}=await import(root+'/public/polling.js');
await pollAgentActivity();
assert.equal(calls.filter(url=>url.includes('/api/ticket-costs')).length,0,'seeing an idle process does not launch codeburn');
revision=1;
await pollAgentActivity();
await new Promise(resolve=>setTimeout(resolve,5));
assert(calls.some(url=>url.includes('/api/ticket-costs?refresh=true')),'new PTY output triggers one fresh cost snapshot');
const costCalls=calls.filter(url=>url.includes('/api/ticket-costs')).length;
await pollAgentActivity();
await new Promise(resolve=>setTimeout(resolve,5));
assert.equal(calls.filter(url=>url.includes('/api/ticket-costs')).length,costCalls,'an unchanged activity revision does not refresh costs');
hidden=true;
const before=calls.length;
revision=2;
await pollAgentActivity();
assert.equal(calls.length,before,'hidden tabs suspend polling');
console.log('resource-polling.mjs OK');
